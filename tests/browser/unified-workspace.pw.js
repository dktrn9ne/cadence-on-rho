import { test, expect } from '@playwright/test';
test('hackathon scenario preserves reservations and enforces the last daily request',async({page})=>{
  await page.goto('/?app=demo');
  await page.getByRole('button',{name:'Load hackathon scenario',exact:true}).click();
  await expect(page.getByRole('button',{name:'Load hackathon scenario',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Payout requests',exact:true}).click();
  await page.getByRole('button',{name:'Review payout',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('$40.00');
  await page.getByRole('button',{name:'Simulate confirmed payout',exact:true}).click();
  await page.getByRole('button',{name:'Worker earnings',exact:true}).click();
  await page.getByRole('textbox',{name:'Payout amount',exact:true}).fill('15');
  await page.getByRole('button',{name:'Request payout →',exact:true}).click();
  await expect(page.getByText('0 / 3',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Payment records',exact:true}).click();
  await page.getByRole('button',{name:'Simulate uncertain',exact:true}).click();
  await expect(page.getByText('Needs reconciliation',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:'Load hackathon scenario',exact:true})).toBeDisabled();
});
test('unified workspace links earnings, daily requests, approval, and settlement records',async({page})=>{
  await page.goto('/?app=demo');
  await expect(page.getByRole('heading',{name:'Money in rhythm.'})).toBeVisible();
  await page.getByRole('button',{name:'Payroll & team',exact:true}).click();
  await page.getByRole('button',{name:'Load sample work · 2 hours'}).click();
  await page.getByRole('button',{name:'Worker earnings',exact:true}).click();
  await expect(page.getByText('$38.40',{exact:true}).first()).toBeVisible();
  await page.getByRole('textbox',{name:'Payout amount',exact:true}).fill('10');
  await page.getByRole('button',{name:'Request payout →',exact:true}).click();
  await expect(page.getByText('$28.40',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Payout requests',exact:true}).click();
  await page.getByRole('button',{name:'Review payout',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('10.00 RLUSD');
  await page.getByRole('button',{name:'Simulate confirmed payout'}).click();
  await expect(page.getByText('Demo paid',{exact:true})).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:'Payment records',exact:true}).click();
  await expect(page.getByText('Demo paid',{exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
